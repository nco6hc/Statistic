# 1. Hierarchical Bayesian
# ══════════════════════════════════════════════════════════════════════════════

class HierarchicalBayesian:
    """
    Beta-Binomial with empirical Bayes global hyperprior.

    Generative model:
        μ₀, κ₀  ← estimated from training data (Method of Moments)
        θ_s     ~ Beta(μ₀·κ₀,  (1-μ₀)·κ₀)       ← student prior
        x_s     ~ Bernoulli(θ_s)                  ← observation

    Posterior (conjugate):
        θ_s | data ~ Beta(μ₀·κ₀ + S_s,  (1-μ₀)·κ₀ + F_s)

    Key property:
        κ₀ controls shrinkage. Rare students (small n_s) are pulled toward
        μ₀; frequent students dominate their own data.
        The existing BB uses a fixed uniform prior (κ = 2); here κ is
        data-driven and can be much larger (stronger pooling).
    """

    def __init__(self, n_students: int = 55):
        base = 6.0 / n_students
        self.mu0   = base
        self.kappa = 10.0
        self.N     = n_students
        self.S = np.zeros(n_students, dtype=np.float64)
        self.F = np.zeros(n_students, dtype=np.float64)

    def _alpha0(self) -> float:
        return self.mu0 * self.kappa

    def _beta0(self) -> float:
        return (1.0 - self.mu0) * self.kappa

    def fit(self, binary: np.ndarray) -> None:
        n_days = len(binary)
        rates  = binary.mean(axis=0)

        # Method of Moments: E[θ] = μ₀, Var[θ] = μ₀(1-μ₀)/(κ₀+1)
        self.mu0 = float(rates.mean())
        var = float(rates.var())
        if var > 1e-8:
            kappa_mom = self.mu0 * (1.0 - self.mu0) / var - 1.0
            self.kappa = float(np.clip(kappa_mom, 2.0, 500.0))

        # Warm-start posteriors with all training data
        self.S = binary.sum(axis=0).astype(np.float64)
        self.F = (n_days - binary.sum(axis=0)).astype(np.float64)

        print(f"    μ₀={self.mu0:.4f}  κ₀={self.kappa:.1f}  "
              f"α₀={self._alpha0():.2f}  β₀={self._beta0():.2f}")
        pm = self._posterior_mean()
        print(f"    Posterior mean range: [{pm.min():.4f}, {pm.max():.4f}]")

    def _posterior_mean(self) -> np.ndarray:
        a = self._alpha0() + self.S
        b = self._beta0()  + self.F
        return (a / (a + b)).astype(np.float32)

    def predict(self) -> list[list[int]]:
        return _groups_from_probs(self._posterior_mean())

    def update(self, obs: np.ndarray) -> None:
        self.S += obs.astype(np.float64)
        self.F += (1.0 - obs).astype(np.float64)


