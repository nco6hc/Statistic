"""
Advanced Bayesian Methods Comparison
======================================

Three methods that differ fundamentally from the existing Bayesian BB:

  Existing BB:  Per-student Beta posteriors + temporal decay (γ=0.97)
                + cooldown penalty + empirical Bayes hyperprior refresh

  NEW ─────────────────────────────────────────────────────────────────
  1. Hierarchical Bayesian (HB)
       Students share a global hyperprior estimated from training data.
       "Partial pooling" — rare students borrow strength from frequent ones.
       Hyperparameters μ₀, κ₀ estimated via Method of Moments (empirical Bayes).
       No cooldown, no decay. Pure structural prior.

  2. Dirichlet Process Mixture (DPM)
       Non-parametric clustering: students grouped by selection pattern.
       Each cluster k has Beta(a_k, b_k) calling probability.
       Students are soft-assigned to clusters via variational EM.
       Prediction: P(s) = Σ_k r[s,k] · θ_k  (marginalised over clusters)
       New clusters can capture teacher "favourite groups" patterns.

  3. Pure Thompson Sampling (PTS)
       No decay, no cooldown. Beta-Binomial conjugate with uniform prior.
       Groups generated by sampling θ ~ Beta(α, β) → top-6.
       Each candidate group is independent → natural diversity.
       Cleanest comparison: what does Thompson Sampling alone buy?

Benchmarks (100-day fair evaluation):
  Bayesian BB   = 26.33%
  Hybrid Orig   = 26.83%

Usage:
    cd dl_pipeline
    python advanced_bayesian/run_advanced_bayesian.py
"""

from __future__ import annotations
import sys
from pathlib import Path

_THIS_DIR = Path(__file__).resolve().parent
_DL_DIR   = _THIS_DIR.parent
sys.path.insert(0, str(_DL_DIR))

import numpy as np
import pandas as pd
import time

# ── Config ────────────────────────────────────────────────────────────────────
SEED = 42
np.random.seed(SEED)
RNG  = np.random.default_rng(SEED)

CFG = {
    'excel_path':    str(_DL_DIR.parent / 'Database.xlsx'),
    'n_students':    55,
    'k':             6,
    'n_groups':      5,
    'train_ratio':   0.9,
    'n_sim_days':    100,
    'temperature':   1.5,
}

BENCHMARKS = {
    'Bayesian BB  (existing)': 26.33,
    'Hybrid Orig  (existing)': 26.83,
}


# ── Data ──────────────────────────────────────────────────────────────────────

def load_binary() -> np.ndarray:
    df = pd.read_excel(CFG['excel_path'])
    df = df.sort_values('Days').reset_index(drop=True)
    n_days = len(df)
    binary = np.zeros((n_days, CFG['n_students']), dtype=np.float32)
    id_cols = [c for c in df.columns if c.startswith('Student ID')]
    for row_idx, row in df.iterrows():
        for col in id_cols:
            sid = int(row[col]) - 1
            if 0 <= sid < CFG['n_students']:
                binary[row_idx, sid] = 1.0
    return binary


# ── Shared helpers ────────────────────────────────────────────────────────────

def _groups_from_probs(probs: np.ndarray) -> list[list[int]]:
    """Temperature-scaled diverse group generation (n_groups candidates)."""
    N, k, ng, T = CFG['n_students'], CFG['k'], CFG['n_groups'], CFG['temperature']
    p = np.clip(probs, 1e-9, None) ** (1.0 / T)
    p /= p.sum()
    groups: list[list[int]] = []
    for _ in range(ng * 4):
        g = sorted(np.random.choice(N, k, replace=False, p=p).tolist())
        if g not in groups:
            groups.append(g)
        if len(groups) >= ng:
            break
    if not groups:
        groups.append(sorted(np.argsort(probs)[-k:].tolist()))
    return groups[:ng]


def _best_overlap(groups: list[list[int]], actual: set) -> float:
    return max(len(set(g) & actual) for g in groups) / CFG['k']


