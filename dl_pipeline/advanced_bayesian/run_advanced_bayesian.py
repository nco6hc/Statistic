# 3. Pure Thompson Sampling
# ══════════════════════════════════════════════════════════════════════════════

class PureThompsonSampling:
    """
    Beta-Binomial Thompson Sampling — no decay, no cooldown, no clustering.

    Difference from existing BB:
        - BB uses decay γ=0.97 (recent days weighted more)
        - BB applies cooldown δ after selection
        - BB periodically refreshes hyperpriors

    PTS has NONE of those — raw Beta posteriors updated uniformly.
    This tests whether the BB's extra complexity (decay+cooldown+EB) helps,
    or if simple conjugate TS suffices.

    Group generation:
        Repeat n_groups×4 times:
            θ_s ~ Beta(α_s, β_s) for all 55 students
            group = top-6(θ)
        Keeps up to n_groups unique groups.
    """

    def __init__(self, n_students: int = 55, prior_strength: float = 2.0):
        base         = 6.0 / n_students
        self.alpha   = np.full(n_students, base * prior_strength,
                               dtype=np.float64)
        self.beta_   = np.full(n_students, (1.0 - base) * prior_strength,
                               dtype=np.float64)
        self.rng     = np.random.default_rng(SEED)

    def fit(self, binary: np.ndarray) -> None:
        self.alpha  += binary.sum(axis=0).astype(np.float64)
        self.beta_  += (len(binary) - binary.sum(axis=0)).astype(np.float64)
        pm = self.alpha / (self.alpha + self.beta_)
        print(f"    PTS posterior mean: [{pm.min():.4f}, {pm.max():.4f}]")
        print(f"    PTS α range: [{self.alpha.min():.1f}, {self.alpha.max():.1f}]")

    def predict(self) -> list[list[int]]:
        groups: list[list[int]] = []
        ng = CFG['n_groups']
        for _ in range(ng * 4):
            theta = self.rng.beta(self.alpha, self.beta_)
            g     = sorted(np.argsort(theta)[-CFG['k']:].tolist())
            if g not in groups:
                groups.append(g)
            if len(groups) >= ng:
                break
        if not groups:
            pm = self.alpha / (self.alpha + self.beta_)
            groups.append(sorted(np.argsort(pm)[-CFG['k']:].tolist()))
        return groups[:ng]

    def update(self, obs: np.ndarray) -> None:
        self.alpha  += obs.astype(np.float64)
        self.beta_  += (1.0 - obs).astype(np.float64)


# ══════════════════════════════════════════════════════════════════════════════
# Simulation runner
# ══════════════════════════════════════════════════════════════════════════════

def simulate(model, binary: np.ndarray, split: int, label: str) -> np.ndarray:
    n_sim = min(CFG['n_sim_days'], len(binary) - split)
    accs  = []
    t0    = time.perf_counter()

    for i in range(n_sim):
        actual = set(np.where(binary[split + i] == 1)[0].tolist())
        groups = model.predict()
        acc    = _best_overlap(groups, actual)
        accs.append(acc)

        if (i + 1) in {1, 10, 25, 50, 75, 100}:
            print(f"    Day {i+1:3d}: {acc*100:.1f}%  actual={sorted(actual)}")

        model.update(binary[split + i])

    arr = np.array(accs) * 100.0
    print(f"\n  ── {label} ──")
    print(f"  Avg: {arr.mean():.2f}%  Best: {arr.max():.2f}%  "
          f"Worst: {arr.min():.2f}%  Std: {arr.std():.4f}")
    dist = {k: int((arr == k / 6 * 100).sum()) for k in range(7)}
    non_zero = {k: v for k, v in dist.items() if v > 0}
    print(f"  Dist: " + "  ".join(f"{k}/6={v}" for k, v in non_zero.items()))
    print(f"  Time: {time.perf_counter()-t0:.1f}s")
    return arr


