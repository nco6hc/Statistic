# 2. Dirichlet Process Mixture
# ══════════════════════════════════════════════════════════════════════════════

class DirichletProcessMixture:
    """
    Truncated Dirichlet Process Mixture (K_max clusters, stick-breaking).

    Generative model:
        V_k     ~ Beta(1, α_DP)                ← stick lengths
        π_k      = V_k · Π_{j<k}(1−V_j)         ← cluster weights
        θ_k     ~ Beta(a₀, b₀)               ← cluster calling probability
        z_s     ~ Categorical(π)              ← student cluster assignment
        x_s     ~ Bernoulli(θ_{z_s})          ← observation

    Inference:
        Variational EM — E-step (soft assignments) + M-step (cluster params)
        run for n_iter iterations on training data, then online after each day.

    Key property:
        Captures "teacher groups" — if the teacher tends to call certain
        clusters of students together, DPM clusters them and predicts them
        jointly via soft assignments.
    """

    def __init__(self, n_students: int = 55, K_max: int = 8,
                 alpha_dp: float = 2.0):
        self.N        = n_students
        self.K        = K_max
        self.alpha_dp = alpha_dp
        base          = 6.0 / n_students

        # Cluster Beta parameters
        self.a = np.ones(K_max, dtype=np.float64) * base * 20.0
        self.b = np.ones(K_max, dtype=np.float64) * (1.0 - base) * 20.0

        # Soft assignments (N × K) and cluster weights
        self.r  = np.ones((n_students, K_max), dtype=np.float64) / K_max
        self.pi = np.ones(K_max, dtype=np.float64) / K_max

        # Cumulative stats for online updates
        self.S_total = np.zeros(n_students, dtype=np.float64)
        self.n_total = 0.0

    def fit(self, binary: np.ndarray, n_iter: int = 30) -> None:
        n_days         = len(binary)
        self.S_total   = binary.sum(axis=0).astype(np.float64)
        self.n_total   = float(n_days)
        rates          = self.S_total / n_days

        # Initialise cluster means at evenly-spaced quantiles of student rates
        quantiles = np.percentile(rates, np.linspace(5, 95, self.K))
        for k, mu_k in enumerate(quantiles):
            mu_k = float(np.clip(mu_k, 0.01, 0.99))
            self.a[k] = mu_k * 20.0
            self.b[k] = (1.0 - mu_k) * 20.0

        # Variational EM
        for _ in range(n_iter):
            theta_k = self.a / (self.a + self.b)                        # (K,)

            # E-step: soft assignments
            log_r = np.zeros((self.N, self.K))
            for k in range(self.K):
                log_r[:, k] = (
                    self.S_total * np.log(theta_k[k] + 1e-10) +
                    (n_days - self.S_total) * np.log(1.0 - theta_k[k] + 1e-10) +
                    np.log(self.pi[k] + 1e-10)
                )
            log_r -= log_r.max(axis=1, keepdims=True)
            r = np.exp(log_r)
            r /= r.sum(axis=1, keepdims=True)
            self.r = r

            # M-step: cluster parameters
            N_k = r.sum(axis=0)                                          # (K,)
            for k in range(self.K):
                ws = float((r[:, k] * self.S_total).sum())
                wf = float((r[:, k] * (n_days - self.S_total)).sum())
                self.a[k] = 1.0 + ws
                self.b[k] = 1.0 + wf

            # VB stick-breaking weight update
            suffix_N  = np.cumsum(N_k[::-1])[::-1]
            beta_vb   = self.alpha_dp + suffix_N - N_k
            V         = (1.0 + N_k) / (1.0 + N_k + beta_vb)
            remaining = np.cumprod(np.concatenate([[1.0], 1.0 - V[:-1]]))
            pi        = V * remaining
            self.pi   = pi / pi.sum()

        theta_k = self.a / (self.a + self.b)
        print(f"    DPM K={self.K}, α_DP={self.alpha_dp}")
        print(f"    Cluster θ: {theta_k.round(3)}")
        print(f"    Cluster π: {self.pi.round(3)}")

    def _predict_probs(self) -> np.ndarray:
        theta_k = self.a / (self.a + self.b)                             # (K,)
        return (self.r * theta_k[None, :]).sum(axis=1).astype(np.float32)

    def predict(self) -> list[list[int]]:
        return _groups_from_probs(self._predict_probs())

    def update(self, obs: np.ndarray) -> None:
        self.S_total += obs.astype(np.float64)
        self.n_total += 1.0

        # Quick E-step
        theta_k = self.a / (self.a + self.b)
        log_r   = np.zeros((self.N, self.K))
        for k in range(self.K):
            log_r[:, k] = (
                self.S_total * np.log(theta_k[k] + 1e-10) +
                (self.n_total - self.S_total) * np.log(1.0 - theta_k[k] + 1e-10) +
                np.log(self.pi[k] + 1e-10)
            )
        log_r -= log_r.max(axis=1, keepdims=True)
        r = np.exp(log_r)
        r /= r.sum(axis=1, keepdims=True)
        self.r = r

        # Quick M-step
        for k in range(self.K):
            ws = float((r[:, k] * self.S_total).sum())
            wf = float((r[:, k] * (self.n_total - self.S_total)).sum())
            self.a[k] = 1.0 + ws
            self.b[k] = 1.0 + wf


